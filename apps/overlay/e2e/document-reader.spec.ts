import { test, expect, layer, expectMode, ready, received, surface } from './fixtures';
import { fakeDaemon, session } from './daemon';
import { openList } from './scenarios';

test('opens a Markdown plan in the same panel and returns to the preserved reply', async ({ page }) => {
  const d = await fakeDaemon(page, [session('otto', { state: 'idle', lastReply: { text: 'Le plan est dans [docs/plan.md](docs/plan.md).', at: new Date().toISOString() } })]);
  await ready(page, 1);
  await openList(page);
  await layer(page, 'list').getByRole('button', { name: /Otto/ }).click();
  await expectMode(page, 'session');
  const reply = layer(page, 'session').locator('[data-reply]');
  await reply.fill('Mon brouillon');
  await layer(page, 'session').getByRole('link', { name: 'docs/plan.md' }).click();
  await expectMode(page, 'reader');
  await expect(surface(page)).toHaveCSS('width', '560px');
  const read = await received(d.received, 'document.read');
  expect(read).toMatchObject({ path: 'docs/plan.md', sessionId: 'otto' });
  d.emit({ type: 'document.content', requestId: read.requestId, path: '/w/harness-assistant/docs/plan.md', text: '# Plan\n\n## Étape\n\n- [ ] À faire\n\n[Suite](suite.md)', bytes: 55, modifiedAt: new Date().toISOString() });
  await expect(layer(page, 'reader').getByRole('heading', { name: 'Plan' })).toBeVisible();
  await layer(page, 'reader').getByRole('button', { name: 'Contents' }).click();
  await expect(layer(page, 'reader').getByRole('navigation', { name: 'Contents' })).toContainText('Étape');
  await layer(page, 'reader').getByRole('button', { name: 'Contents' }).click();
  await layer(page, 'reader').getByRole('link', { name: 'Suite' }).click();
  const child = await received(d.received, 'document.read', m => m.path === 'suite.md');
  expect(child.basePath).toBe('/w/harness-assistant/docs/plan.md');
  d.emit({ type: 'document.error', requestId: child.requestId, path: child.path, code: 'not_found' });
  await expect(layer(page, 'reader').getByRole('alert')).toContainText('File not found');
  await layer(page, 'reader').getByRole('button', { name: 'Retry' }).click();
  const retry = await received(d.received, 'document.read', m => m.path === 'suite.md' && m.requestId !== child.requestId);
  d.emit({ type: 'document.content', requestId: retry.requestId, path: '/w/harness-assistant/docs/suite.md', text: '# Suite', bytes: 7, modifiedAt: new Date().toISOString() });
  await expect(layer(page, 'reader').getByRole('heading', { name: 'Suite' })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(layer(page, 'reader').getByRole('heading', { name: 'Plan' })).toBeVisible();
  await layer(page, 'reader').getByRole('button', { name: 'Contents' }).click();
  await expect(layer(page, 'reader').getByRole('navigation', { name: 'Contents' })).toContainText('Étape');
  await layer(page, 'reader').getByRole('button', { name: 'Contents' }).click();
  await layer(page, 'reader').getByRole('button', { name: 'Markdown' }).click();
  await expect(layer(page, 'reader').locator('[data-document-source]')).toContainText('# Plan');
  await layer(page, 'reader').getByRole('button', { name: 'Expand' }).click();
  await expect(surface(page)).toHaveCSS('width', '800px');
  await page.keyboard.press('Escape');
  await expectMode(page, 'session');
  await expect(reply).toHaveValue('Mon brouillon');
  expect(d.received.some(m => m.type === 'session.reply' || m.type === 'session.decide')).toBe(false);
});
